#!/usr/bin/env python3
"""Writes src/formsGL/formsGLSchemas.h: Forms GL Box's own copy of the generator parameter schemas
(the sketch's generators.json, embedded), so it never reads the sketch's file.
usage: make_schemas.py <generators.json> [out header]
Run it again when a generator's parameters change (and change the C++ port to match)."""
import json, sys
src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else "src/formsGL/formsGLSchemas.h"
g = json.load(open(src))
g["renderer"] = "FormsGL"
text = json.dumps(g, separators=(",", ":"), ensure_ascii=True)
chunks = [text[i:i + 12000] for i in range(0, len(text), 12000)]
with open(out, "w") as f:
    f.write("//\n//  formsGLSchemas.h  (generated by tests/formsGL/make_schemas.py: do not edit)\n")
    f.write("//  ofxOceanodeForms — Forms GL Box's own generator parameter schemas: the ESPECTRES_2027\n")
    f.write("//  sketch's generators.json as of its code %s, embedded so Forms GL Box never needs the sketch.\n//\n\n" % g.get("codeHash", "?"))
    f.write("#pragma once\n\nnamespace formsgl {\n\ninline const char* generatorSchemasJson(){\n    return\n")
    for c in chunks: f.write('        R"FGLS(' + c + ')FGLS"\n')
    f.write("        ;\n}\n\n} // namespace formsgl\n")
print(out, len(text), "bytes in", len(chunks), "chunks")
